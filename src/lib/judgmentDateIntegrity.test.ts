import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * 裁判日期不得被捏造。
 *
 * 實測缺陷：判決書分析在原文完全沒有裁判日期時，
 * 輸出「民國113年」，甚至「民國113年5月20日」這種
 * 原文不存在的完整日期。
 *
 * 根因：提示詞只給了格式範例（民國115年3月15日），
 * 沒有說明找不到時該怎麼辦，模型便照範例捏造一個。
 *
 * 裁判日期決定上訴期限的起算。捏造日期會讓當事人算錯期限
 * 而失去救濟機會——這是本工具最不能出錯的欄位。
 */
const 提示詞 = readFileSync(resolve(process.cwd(), 'src/prompts/analyze-judgment.ts'), 'utf8');

/** 從輸出物件中取出裁判日期欄位。 */
function 裁判日期(輸出: Record<string, unknown>): string {
  const 值 = 輸出.judgeDate;
  return typeof 值 === 'string' ? 值 : String(值 ?? '');
}

/**
 * 判斷輸出的裁判日期是否可信。
 *
 * 僅比對數字不足以抓到捏造：「民國113年」的「113」可能來自原方案號
 * （113年度訴字第1234號），數字集合檢查會誤認為通過。
 * 因此加上完整性判準：非空的裁判日期必須同時有年、月、日，
 * 且每個數字都能在原文找到。
 *
 * 實測觀察到的兩種捏造形狀都會被抓：
 *   「民國113年」        → 不完整（缺月日）
 *   「民國113年5月20日」→ 5 與 20 不在原文
 */
function 日期可信(日期: string, 原文: string): boolean {
  const t = 日期.trim();
  if (!t) return true; // 空字串是正確行為：找不到就不填
  // 完整性：年、月、日三者俱備
  if (!/[年]/.test(t) || !/[月]/.test(t) || !/[日]/.test(t)) return false;
  // 忠實度：每個數字都必須出自原文
  const 輸出數字 = t.match(/\d+/g) || [];
  const 原文數字 = new Set(原文.match(/\d+/g) || []);
  return 輸出數字.every(n => 原文數字.has(n));
}

describe('裁判日期不得捏造', () => {
  it('提示詞必須說明找不到時填空字串', () => {
    expect(提示詞).toMatch(/judgeDate.*填空字串/s);
  });

  it('提示詞必須明確禁止推估或捏造', () => {
    expect(提示詞).toMatch(/嚴禁推估或捏造|不得捏造|嚴禁捏造/);
  });

  it('提示詞必須說明理由（裁判日期決定上訴期限起算）', () => {
    // 讓維護者知道這條規則為什麼存在，避免日後被當成多餘而刪除。
    expect(提示詞).toMatch(/上訴期限|起算|救濟機會/);
  });

  it('驗證邏輯：原文有的日期視為通過，空值也視為通過', () => {
    const 原文 = '裁判日期：中華民國112年3月15日';
    expect(日期可信('民國112年3月15日', 原文)).toBe(true);
    expect(日期可信('', '任何內容')).toBe(true);
  });

  it('驗證邏輯：原文沒有的數字會被抓出來', () => {
    // 這是實際觀察到的缺陷形狀：原文無日期卻輸出完整日期。
    const 原文 = '臺灣臺北地方法院 113 年度訴字第 1234 號民事判決\n主文\n原告之訴駁回。';
    expect(日期可信('民國113年', 原文)).toBe(false);
    expect(日期可信('民國113年5月20日', 原文)).toBe(false);
  });

  it('完整性判準能抓出「民國113年」這種缺月日的捏造', () => {
    // 這是上述驗證的已知限制：民國113年 的「113」在原文中存在（案號），
    // 因此不會被抓出。真正能抓出的是「5月20日」這類原文不存在的組合。
    // 提示詞層的禁止說明才是主要防線，此測試是第二道。
    const 原文 = '113 年度訴字第 1234 號';
    expect(日期可信('民國113年5月20日', 原文)).toBe(false);
  });
});
