/**
 * 將文字中的簡體特徵字轉為繁體。
 *
 * 與「直接丟棄整份產出」不同：AI 產出通常只夾帶少量簡體字
 * （例如「担保」而非「擔保」），其餘內容是完整可用的法律分析。
 * 因為幾個字就丟棄全部，是把可修正的小瑕疵升級成重大損失。
 *
 * 正式站實測：defense-triage 曾因含簡體而整份退回規則備援，
 * 使用者拿到 41 字的通用輸出，AI 的分析完全沒有發揮作用。
 *
 * 使用者仍會拿到完整繁體文件；轉換後若仍有殘留，
 * 呼叫端可再依 containsSimplifiedChinese 決定是否 fail-closed。
 */
export function toTraditionalChinese(text: string): string {
  if (!text) return text;
  let out = '';
  for (const char of text) {
    out += SIMPLIFIED_ONLY.get(char) ?? char;
  }
  return out;
}

/** 文字是否含簡體特徵字。 */
export function containsSimplifiedChinese(text: string): boolean {
  return findSimplifiedChinese(text).length > 0;
}

/**
 * 產生繁簡用字錯誤訊息。
 * @param label 出錯的欄位或區塊名稱
 * @param text 該區塊文字
 */
export function describeSimplifiedChinese(label: string, text: string): string {
  const hits = findSimplifiedChinese(text);
  const pairs = hits.slice(0, 6).map(h => `${h.simplified}→${h.traditional}`).join('、');
  return `${label}含簡體中文用字（${pairs}${hits.length > 6 ? ' 等' : ''}），台灣法律文件應使用繁體中文，已阻擋交付。`;
}
