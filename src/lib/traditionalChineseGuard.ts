/**
 * 繁體中文用字檢查。
 *
 * 背景：本系統所有提示詞原本沒有要求繁體中文，模型便偶爾以簡體中文回覆。
 * 實測曾出現補充事實選項為「已签书面合同并有转账记录」，該文字會被併入
 * 案件事實，並進一步帶入產製的法律書狀。台灣法律文件出現簡體字是正確性缺陷。
 *
 * 設計取捨：本模組只「偵測」，不做繁簡轉換。
 * 繁簡並非一對一（发可對應發／髮、后可對應後／后、干可對應幹／乾／干），
 * 自行維護半套對照表在法律用字上風險高於收益：錯轉會靜默產出錯誤法律文字。
 * 因此採兩段式處理：
 *   1. 提示詞層強制繁體中文（消除成因，見 prompts/legalProcessPrompts.ts）；
 *   2. 本模組在產出邊界做確定性檢查，發現簡體字即 fail-closed，不讓它進入交付。
 *
 * 收錄原則：只列「僅存在於簡體字形、在繁體中文中不會出現」的確定性特徵字，
 * 排除繁簡同形的字（如「台」用於地名時兩邊都常見），以免誤判。
 *
 * 實測教訓：曾誤收「准」，但「准」在繁體中文是合法用字（准許、批准、獲准），
 * 對應的「準」只用在標準一詞。誤收會讓正當的繁體法律文件被交付閘門擋下。
 * 因此一對多或兩邊通用的字一律不收；新增條目前必須先確認該字在繁體中文
 * 不會獨立出現。
 */

