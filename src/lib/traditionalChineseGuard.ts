/**
 * 找出文字中的簡體特徵字。
 * @param text 待檢查文字
 * @returns 去重後的「簡體字→繁體」對照，依出現順序排列
 */
export function findSimplifiedChinese(text: string): Array<{ simplified: string; traditional: string }> {
  if (!text) return [];
  const seen = new Set<string>();
  const hits: Array<{ simplified: string; traditional: string }> = [];
  for (const char of text) {
    const traditional = SIMPLIFIED_ONLY.get(char);
    if (traditional && !seen.has(char)) {
      seen.add(char);
      hits.push({ simplified: char, traditional });
    }
  }
  return hits;
}

/** 文字是否含簡體特徵字。 */
export function containsSimplifiedChinese(text: string): boolean {
  return findSimplifiedChinese(text).length > 0;
}

/**
 * 產生繁簡用字錯誤訊息。
 * @param label 出錯的欄位或區塊名稱
 * @param text 該區塊文字
 */
export function describeSimplifiedChinese(label: string, text: string): string {
  const hits = findSimplifiedChinese(text);
  const pairs = hits.slice(0, 6).map(h => `${h.simplified}→${h.traditional}`).join('、');
  return `${label}含簡體中文用字（${pairs}${hits.length > 6 ? ' 等' : ''}），台灣法律文件應使用繁體中文，已阻擋交付。`;
}
