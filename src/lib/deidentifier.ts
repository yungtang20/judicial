export const scrubPersonalInfo = (text: string): string => {
  if (!text) return text;
  let res = text;
  // 遮蔽身分證字號
  res = res.replace(/[A-Z][1289]\d{8}/g, 'A1********');
  // 遮蔽手機號碼
  res = res.replace(/09\d{8}/g, '09********');
  res = res.replace(/09\d{2}-\d{3}-\d{3}/g, '09**-***-***');
  // 遮蔽市內電話
  res = res.replace(/0\d{1,2}-\d{3,4}-\d{4}/g, '0*-****-****');
  
  // 遮蔽地址 (縣市/鄉鎮市區段)
  res = res.replace(/([一-龥]{2}[縣市])(?:([一-龥]{1,3}[鄉鎮市區])([^，。\n]{1,20})|([^，。\n]{1,20}))/g, (match, p1, p2) => {
    if (p2) return `${p1}${p2}***`;
    return `${p1}***`;
  });
  // 姓名去識別化。
  //
  // 先前規則是「1~3 個中文字 + 稱謂」，導致任何接在稱謂前的法律用語
  // 都被挖掉——實測正式站的律師助理回覆出現：
  //   「主張侵權行為之原告」→「主張侵權◯◯◯原告」
  //   「原告王○○訴請被告張○○」→「原告王○○◯◯◯被告張○○」
  // 「訴請」「行為之」都是法律常用語，遮蔽它們會改變法律文字的意思。
  // 因此先排除常見的法律與虛詞，再判定是否為姓名。
  const 非姓名 = new Set([
    '訴請', '起訴', '共同', '單獨', '代表', '代位', '擬', '本', '是', '為',
    '及', '與', '或', '之', '對', '其', '被', '原', '上訴', '公訴', '自訴',
    '兼', '同', '前', '原告知', '相對', '受', '該', '另', '次',
  ]);

  /**
   * 以結構助詞結尾的片段幾乎不可能是姓名。
   * 「行為之原告」的「行為之」、「公訴人對被告」的「訴人對」
   * 都屬此類，靠列舉詞彙擋不住。
   */
  const 結構助詞 = /[之對的與及或在為是於從被把讓給跟和同]$/;

  res = res.replace(
    /([一-龥]{1,4})(先生|女士|原告|被告|上訴人|被上訴人)/g,
    (match, 候選: string, 稱謂: string) => {
      // 候選詞是法律用語、虛詞或以結構助詞結尾時保留。
      if (非姓名.has(候選) || 結構助詞.test(候選)) return match;
      return `◯◯◯${稱謂}`;
    },
  );

  return res;
};
