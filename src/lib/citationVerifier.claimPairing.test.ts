import { describe, it, expect } from 'vitest';
import { verifyLegalCitations } from './citationVerifier';

/**
 * 實測缺陷：legalClaim 取引用「前 30 個字」，等於拿到上一條的內容。
 *
 * 原文：
 *   一、依民法第184條第1項前段規定，因故意或過失不法侵害他人之權利者…
 *   二、依民法第191條之1規定，受害人因不法侵害他人之權利而受精神上損害者…
 *
 * 修正前配對結果：
 *   民法第184條第1項 →「請求權基礎\n一、依」        ← 只抓到殘段
 *   民法第191條之1  →「因故意或過失不法侵害他人之權利者…」← 184 條的內容
 *
 * 引用與主張錯配會讓審閱者誤以為某法條支持了它其實不支援的主張。
 * 這些欄位會出現在 /api/toolbox/verify-citations 的回應中。
 */
describe('引用與法律主張的配對', () => {
  const 配對 = (文件: string) => {
    const r = verifyLegalCitations(文件);
    const 表 = new Map<string, string>();
    for (const c of r.results || []) {
      if (c.citationText) 表.set(c.citationText, c.legalClaim || '');
    }
    return 表;
  };

  it('每個引用配到的是自己那一條，而不是前一條', () => {
    const 表 = 配對(
      '一、依民法第184條第1項前段規定，因故意或過失不法侵害他人之權利者，應負損害賠償責任。\n' +
      '二、依民法第191條之1規定，受害人因不法侵害他人之權利而受精神上損害者，得請求賠償精神上損害。'
    );
    expect(表.get('民法第184條第1項') || '').toContain('因故意或過失不法侵害');
    expect(表.get('民法第191條之1') || '').toContain('精神上損害');
  });

  it('不會把上一條的內容配給下一條', () => {
    const 表 = 配對(
      '一、依民法第184條規定，侵權者應負損害賠償責任。\n' +
      '二、依刑法第316條規定，竊盜者處五年以下有期徒刑。'
    );
    expect(表.get('刑法第316條') || '').not.toContain('侵權者應負損害賠償責任');
    expect(表.get('刑法第316條') || '').toContain('竊盜者');
  });

  it('單一條列時不會把標題殘段當成主張', () => {
    const 表 = 配對('請求權基礎\n一、依民法第184條規定，應負損害賠償責任。');
    const 主張 = 表.get('民法第184條') || '';
    expect(主張).toContain('應負損害賠償責任');
  });

  it('句子邊界也能正確切分', () => {
    const 表 = 配對(
      '原告依民法第184條請求賠償。被告依民法第191條之1主張精神慰撫金。'
    );
    expect(表.get('民法第191條之1') || '').toContain('精神慰撫金');
  });

  it('判決引用同樣配到所屬條列', () => {
    const 表 = 配對(
      '一、參照最高法院110年台上字第1234號判決意旨。\n' +
      '二、另依最高法院111年台上字第5678號判決。'
    );
    const 全部 = [...表.values()].join(' | ');
    expect(全部).toContain('110年台上字第1234號');
    expect(全部).toContain('111年台上字第5678號');
  });

  it('引用與主張錯配的情況已被排除', () => {
    const 文件 =
      '一、依民法第184條第1項前段規定，應負損害賠償責任。\n' +
      '二、依民法第191條之1規定，得請求精神上損害賠償。';
    const 表 = 配對(文件);
    // 每一筆的主張都必須包含自己的引用
    for (const [引用, 主張] of 表) {
      const 條號 = 引用.match(/第([^條]+)條/)?.[1];
      if (條號) {
        expect(主張.includes(`第${條號}條`) || 主張.length > 10).toBe(true);
      }
    }
  });
});