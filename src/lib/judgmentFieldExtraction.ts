/**
 * 判決書的確定性欄位抽取。
 *
 * 實測缺陷：AI 對法院名稱與審級的抽取錯誤率很高。
 * 四個真實格式的測試中，三個錯誤：
 *   「臺灣高等法院 111 年度上訴字第 2345 號」→ 原審: 臺灣地方法院、審級: 第一審
 *   「最高法院 110 年度台上字第 1234 號」     → 原審: 臺灣地方法院、審級: 第一審
 *   連續四次都給出相同的「臺灣地方法院／第一審判決」，
 *   顯然是照抄提示詞裡的範例「臺灣新北地方法院」，而非讀取原文。
 *
 * 為什麼後果嚴重：審級判錯會讓上訴法院判錯，
 * 使用者可能把第二審判決當第一審處理而漏掉上訴；
 * 或者向錯誤的法院提起救濟程序。
 *
 * 法院名稱與案號在真實判決書的開頭就寫著，
 * 用規則抽取是確定性的，不該交給語言模型猜測。
 */

/** 各級法院的名稱樣式。順序有意義：最高優先，避免「高等法院」被當成「地方法院」。 */
const 法院樣式: Array<{ 樣式: RegExp; 審級: string }> = [
  { 樣式: /最高法院/, 審級: '第三審判決' },
  { 樣式: /臺灣高等法院[^\s]{0,6}?分院/, 審級: '第二審判決' },
  { 樣式: /臺灣高等法院/, 審級: '第二審判決' },
  { 樣式: /[一-龥]{2,4}高等法院/, 審級: '第二審判決' },
  { 樣式: /[一-龥]{2,4}地方法院/, 審級: '第一審判決' },
  { 樣式: /[一-龥]{2,4}方法院/, 審級: '第一審判決' },
  { 樣式: /[一-龥]{2,4}行政法院/, 審級: '第一審判決' },
  { 樣式: /[一-龥]{2,4}簡易庭/, 審級: '第一審判決' }
];

export interface 確定性欄位 {
  法院: string | null;
  案號: string | null;
  審級: string | null;
}

/**
 * 從判決書文字中抽取法院、案號與審級。
 *
 * 只處理能確定比對的部分：
 * - 法院：取原文出現的完整名稱（含分院），不做補字或改寫
 * - 案號：年度 + 案由代號 + 字 + 第 + 號碼
 * - 審級：由法院層級推導（最高→三審、高等→二審、地方法院→一審）
 */
export function 抽取確定性欄位(原文: string): 確定性欄位 {
  if (typeof 原文 !== 'string' || !原文) {
    return { 法院: null, 案號: null, 審級: null };
  }

  let 法院: string | null = null;
  let 審級: string | null = null;
  for (const { 樣式, 審級: 等級 } of 法院樣式) {
    const m = 原文.match(樣式);
    if (m) {
      法院 = m[0];
      審級 = 等級;
      break;
    }
  }

  // 案號：113年度訴字第1234號 / 111年度上訴字第2345號 / 110年度台上字第1234號
  const 案號 = 原文.match(/(\d{2,3}\s*年度\s*[^\s]{1,5}?\s*字?\s*第\s*\d+\s*號)/)?.[0]?.replace(/\s+/g, '') ?? null;

  return { 法院, 案號, 審級 };
}

/**
 * 以確定性抽取校正 AI 輸出。
 *
 * 只在規則能抽到值時覆蓋——抽不到就保留 AI 的結果，
 * 不用空值去清掉它可能抽對的內容。
 */
export function 校正法院欄位(
  ai輸出: Record<string, unknown>,
  原文: string
): Record<string, unknown> {
  const 確定 = 抽取確定性欄位(原文);
  const 修正 = { ...ai輸出 };
  const 變更: string[] = [];

  if (確定.法院 && 確定.法院 !== ai輸出.courtName) {
    變更.push(`courtName ${String(ai輸出.courtName)} → ${確定.法院}`);
    修正.courtName = 確定.法院;
  }
  if (確定.案號 && 確定.案號 !== ai輸出.caseNo) {
    變更.push(`caseNo ${String(ai輸出.caseNo)} → ${確定.案號}`);
    修正.caseNo = 確定.案號;
  }
  if (確定.審級 && 確定.審級 !== ai輸出.courtLevel) {
    變更.push(`courtLevel ${String(ai輸出.courtLevel)} → ${確定.審級}`);
    修正.courtLevel = 確定.審級;
  }

  if (變更.length) {
    修正.deterministicFieldCorrections = 變更;
  }
  return 修正;
}
