import { describe, expect, it } from 'vitest';
import { 篩選可用建議 } from './unifiedWorkflow';

/**
 * 建議選項的品質閘門。
 *
 * 實測正式站，模型把以下內容當成「建議」回傳：
 *   ["Agnes-3.0-flash", "Sapiens AI"]
 *   ["無效輸入格式", "提供的「案件事實」無法計算出具體請求金額…"]
 * 使用者會在「發生日期」欄位看到「Agnes-3.0-flash」。
 *
 * 這些都不是可填入表單的具體值，寧可回報取不到也不能送出去。
 */
describe('建議選項的品質閘門', () => {
  it('模型的自我介紹不得成為建議', () => {
    expect(篩選可用建議(['Agnes-3.0-flash', 'Sapiens AI'])).toEqual([]);
    expect(篩選可用建議(['我是 GPT', '我是一個 AI 助手'])).toEqual([]);
  });

  it('拒絕語不得成為建議', () => {
    expect(篩選可用建議(['無效輸入格式', '提供的案件事實無法計算出具體請求金額'])).toEqual([]);
    expect(篩選可用建議(['請提供更多資訊', '不能判斷'])).toEqual([]);
  });

  it('過長的說明文字不得成為建議', () => {
    const 長文 = '這'.repeat(60);
    expect(篩選可用建議([長文])).toEqual([]);
  });

  it('正常的具體值必須保留', () => {
    const 建議 = ['民國113年1月1日', '民國113年2月1日', '民國113年3月1日'];
    expect(篩選可用建議(建議)).toEqual(建議);
  });

  it('混合時只剔除不合格者，保留可用的', () => {
    expect(篩選可用建議(['Agnes-3.0-flash', '臺灣臺北地方法院', '臺灣新北地方法院']))
      .toEqual(['臺灣臺北地方法院', '臺灣新北地方法院']);
  });

  it('不得因殘留的對話語氣而誤刪真實建議', () => {
    // 「請注意時效」這類字樣在法律建議中是合理的，不可一律刪除「請」字。
    const 建議 = ['建議於3個月內行使', '請求時效為2年'];
    expect(篩選可用建議(建議)).toEqual(建議);
  });

  it('空陣列維持空陣列', () => {
    expect(篩選可用建議([])).toEqual([]);
  });
});
