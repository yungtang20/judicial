import { describe, expect, it } from 'vitest';

/**
 * 追問選項的解析與顯示
 *
 * 實測缺陷（正式站，模擬真人操作時發現）：
 *   1. 追問文字原樣顯示，使用者看得到內部語法，例如
 *      「…整個過程？ [選項按鈕] 是，我本人在現場…」
 *   2. 佔位詞「選項按鈕」被當成一個真正的選項，變成一個按鈕
 *   3. 同一個選項被模型重複輸出時沒有去重
 *
 * 這裡直接驗證解析規則。這些規則純粹處理字串格式，
 * 與模型無關，因此測試不需要呼叫 AI。
 */

/** 與 server/routes/legalProcess.ts 相同的解析規則。 */
function 解析(rawMessage: string): { 顯示文字: string; 選項: string[] } {
  const optionMatches = rawMessage.match(/[【\[](?:選項[：:])?\s*([^\]】]+)\s*[\]】]/g) || [];
  const 選項 = [
    ...new Set(
      optionMatches
        .map(m => m.replace(/^[【\[]|[】\]]$/g, '').replace(/^選項[：:]\s*/, '').trim())
        .filter(Boolean)
        .filter(o => o !== '選項按鈕' && o !== '選項')
    )
  ];
  const 顯示文字 = rawMessage
    .replace(/[【\[](?:選項[：:])?\s*[^\]】]+\s*[\]】]/g, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return { 顯示文字, 選項 };
}

describe('追問選項解析', () => {
  it('新版【選項：…】格式能正確取出選項', () => {
    const r = 解析('我已理解您的現況。為了確認適用法規，需要知道事發當下您是否在場。\n【選項：我在現場並全程參與對話】【選項：我不在場，事後才得知】');
    expect(r.選項).toEqual(['我在現場並全程參與對話', '我不在場，事後才得知']);
  });

  it('舊版 […] 格式仍可解析', () => {
    const r = 解析('請問當時的情況為？ [事件發生在最近3天內] [對方是我的配偶或同住家人]');
    expect(r.選項).toEqual(['事件發生在最近3天內', '對方是我的配偶或同住家人']);
  });

  it('顯示文字不得殘留內部語法', () => {
    // 這是實測最直接的缺陷：使用者會看到 [選項按鈕] 這串字。
    const r = 解析('請問您是否在場？ [選項按鈕] [是，我本人在現場] [否，我是事後得知]');
    expect(r.顯示文字).not.toMatch(/[【\[]/);
    expect(r.顯示文字).toContain('請問您是否在場？');
  });

  it('佔位詞不應成為選項', () => {
    const r = 解析('請問？ [選項按鈕] [是] [否]');
    expect(r.選項).not.toContain('選項按鈕');
    expect(r.選項).toEqual(['是', '否']);
  });

  it('重複輸出的選項只保留一次', () => {
    const r = 解析('請問？ [是，我本人在現場目睹或參與對話] [是，我本人在現場目睹或參與對話] [否，我是事後得知]');
    expect(r.選項).toEqual(['是，我本人在現場目睹或參與對話', '否，我是事後得知']);
  });

  it('顯示文字不得殘留多餘空行', () => {
    const r = 解析('問題文字\n\n【選項：甲】【選項：乙】');
    expect(r.顯示文字).not.toMatch(/\n{3,}/);
  });

  it('沒有選項時不影響問題文字', () => {
    const r = 解析('請補充事發當日的具體情況。');
    expect(r.選項).toEqual([]);
    expect(r.顯示文字).toBe('請補充事發當日的具體情況。');
  });
});
