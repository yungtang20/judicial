import { describe, expect, it } from 'vitest';
import { 取出建議選項 } from './unifiedWorkflow';

/**
 * 建議選項必須從模型的多種輸出形狀中取出。
 *
 * 實測正式站：同一個「AI 建議」功能，12 次呼叫只有 2 次成功。
 * 模型會回多種形狀，舊實作只認「直接是陣列」一種，
 * 取不到就回空陣列卻仍回 success:true——
 * 使用者看到「AI 建議」按鈕，點下去什麼都沒有。
 *
 * 這裡鎖住每一種實際觀察到的形狀，避免日後新增模型或改版提示詞時又漏掉。
 */
describe('建議選項的取出', () => {
  it('直接是陣列', () => {
    expect(取出建議選項(['A', 'B', 'C'])).toEqual(['A', 'B', 'C']);
  });

  it('包在 options', () => {
    expect(取出建議選項({ options: ['A', 'B'] })).toEqual(['A', 'B']);
  });

  it('包在 suggestions', () => {
    expect(取出建議選項({ suggestions: ['A', 'B'] })).toEqual(['A', 'B']);
  });

  it('單一描述性欄位是說明文字，不是建議選項', () => {
    // {"note":"我無法提供建議"} 只有一個值，讀起來像模型的說明而非清單。
    // 把它當成選項只會讓使用者拿到一句毫無用處的解釋。
    expect(取出建議選項({ note: '我無法提供建議' })).toEqual([]);
  });

  it('錯誤回應不得被當成建議選項', () => {
    // 實測正式站：建議選項回 ["無法解析請求參數", "400"]——
    // 上游的錯誤物件被當成建議清單送到使用者手上。
    // 使用者會看到「無法解析請求參數」出現在可點選的建議按鈕裡。
    expect(取出建議選項({ error: '無法解析請求參數', code: '400' })).toEqual([]);
    expect(取出建議選項({ message: 'Internal Server Error' })).toEqual([]);
    expect(取出建議選項({ error: '無法解析', status: 400 })).toEqual([]);
  });

  it('含錯誤欄位但也有建議內容時，仍取出建議', () => {
    // 避免規則寫得太寬，把真的建議一起擋掉。
    expect(取出建議選項({ warning: '僅供參考', options: ['甲案', '乙案'] }))
      .toEqual(['甲案', '乙案']);
  });

  it('多個描述性欄位是清單，應當取出', () => {
    // JSON 模式下模型常回 {"選項一":"…","選項二":"…","選項三":"…"}。
    // 這是清單，必須取得，否則建議功能形同失效。
    expect(取出建議選項({ 選項一: '甲案', 選項二: '乙案', 選項三: '丙案' }))
      .toEqual(['甲案', '乙案', '丙案']);
  });

  it('數字鍵的物件仍可取出', () => {
    expect(取出建議選項({ '1': '甲方案', '2': 300 })).toEqual(['甲方案', '300']);
  });


  it('去掉空白項', () => {
    expect(取出建議選項(['A', '', '  ', 'B'])).toEqual(['A', 'B']);
  });

  it('過長的項目視為無效（不會是欄位建議）', () => {
    expect(取出建議選項(['A', '長'.repeat(500)])).toEqual(['A']);
  });

  it('取不到內容時回空陣列', () => {
    // 空陣列是「取不到」的明確訊號，讓呼叫端據此回報失敗，
    // 而不是回 success 搭配空白按鈕。
    expect(取出建議選項(null)).toEqual([]);
    expect(取出建議選項(undefined)).toEqual([]);
    expect(取出建議選項({})).toEqual([]);
    expect(取出建議選項('純文字')).toEqual([]);
  });
});
