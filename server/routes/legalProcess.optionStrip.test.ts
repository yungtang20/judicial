import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * 追問文字不得殘留內部語法。
 *
 * 實測缺陷（間歇性）：4 次取樣中有 1 次，畫面出現
 * 「選項按鈕：甲、選項按鈕：乙」這類內部語法。
 *
 * 根因：原先的剝除規則只處理帶書名號的形式
 * （【選項：甲】、[選項：甲]），對模型偶爾輸出的
 * 無書名號形式完全無效。
 *
 * 這裡直接從原始碼擷取實際使用的規則來驗證，
 * 避免測試與實作各寫一份而分歧。
 */
const 原始碼 = readFileSync(resolve(process.cwd(), 'server/routes/legalProcess.ts'), 'utf8');
const 規則1 = 原始碼.match(/(\.replace\(\/\[【\\\[\][^\n]*\/g, ''\))/);
const 規則2 = 原始碼.match(/(\.replace\(\/\(\?:\^\|\[[^\n]*\/g, \(m\) =>[^\n]*\))/);

function 剝除(s: string): string {
  if (!規則1 || !規則2) throw new Error('無法從原始碼擷取剝除規則');
  return new Function(
    's',
    `return s${規則1[1]}${規則2[1]}.replace(/[ \\t]{2,}/g,' ').replace(/\\n{3,}/g,'\\n\\n').trim();`
  )(s);
}

describe('追問文字的內部語法剝除', () => {
  it('剝除規則可從原始碼擷取（測試與實作不分離）', () => {
    expect(規則1, '找不到帶書名號的剝除規則').toBeTruthy();
    expect(規則2, '找不到無書名號的剝除規則').toBeTruthy();
  });

  it.each([
    ['帶書名號', '【選項：甲】【選項：乙】'],
    ['半形方括號', '[選項：甲]'],
    ['無書名號（實測的洩漏形式）', '選項按鈕：甲、選項按鈕：乙'],
    ['句中的無書名號', '請問當時情況？選項按鈕：甲'],
    ['句中的帶書名號', '請問當時情況？【選項：甲】'],
    ['句尾的無書名號', '為何如此？選項：甲'],
    ['獨立一行', '選項：甲']
  ])('%s 形式必須被完全剝除', (_名, 輸入) => {
    expect(剝除(輸入)).not.toMatch(/選項/);
  });

  it('正常追問文字不得被破壞', () => {
    const 正常 = '為了判斷適用法規，需要知道事發當下的具體情況，請說明。';
    expect(剝除(正常)).toBe(正常);
  });

  it('問題文字應保留，只移除選項標記', () => {
    expect(剝除('請問當時情況？【選項：甲】')).toBe('請問當時情況？');
  });

  it('不含「選項」二字的內容必須原樣保留', () => {
    for (const s of ['本案件涉及選擇權問題。', '請問您的選擇是什麼？', '選舉法相關爭議。']) {
      expect(剝除(s), `誤刪了正常內容：${s}`).toBe(s);
    }
  });
});
